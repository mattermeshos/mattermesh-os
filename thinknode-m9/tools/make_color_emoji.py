"""T-Deck Plus colour emoji: Noto Color Emoji (OFL, assets/fonts/NotoColorEmoji.ttf, CBDT bitmaps) -> RGB565 sprites.

src/ui/emoji_color.h  20 px sprites for every chat emoji of assets/config/chat-emoji.txt and 30 px sprites for the
                      composer picker (src/ui/emoji_picker.h); smaller emoji (16 px names and previews) are averaged
                      down from the 20 px set at draw time (mm::FastCanvas16::drawRGBAArea). Pixels are RGB565 in the LCD panel byte order
                      (mm::rgb), alpha is 4-bit coverage (two pixels per byte, high nibble first); drawn by
                      mm::FastCanvas16::drawRGBA. Each sprite (RGB565 words, little endian, then the alpha bytes) is
                      raw-deflated on its own and inflated at draw time (src/ui/packed.h). Codepoints the font lacks
                      are left out.
Run with the tools venv: python tools/make_color_emoji.py
"""
import re
import struct
import zlib
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "assets/fonts/NotoColorEmoji.ttf"
font = ImageFont.truetype(str(FONT), 109)  # CBDT strike size

chat_codes = sorted(int(l, 16) for l in (ROOT / "assets/config/chat-emoji.txt").read_text().splitlines() if l.strip() and not l.startswith("#"))
picker_codes = [int(c) for c in re.findall(r"\{(\d+),\"", (ROOT / "src/ui/emoji_picker.h").read_text())]


def render(cp, size):
    ch = chr(cp)
    im = Image.new("RGBA", (160, 160), (0, 0, 0, 0))
    try:
        ImageDraw.Draw(im).text((8, 8), ch, font=font, embedded_color=True)
    except Exception:
        return None
    bbox = im.getbbox()
    if bbox and bbox[2] - bbox[0] < 20:  # a lone variation selector or a missing glyph box
        return None
    if not bbox:
        return None
    im = im.crop(bbox)
    side = max(im.width, im.height)
    square = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    square.paste(im, ((side - im.width) // 2, (side - im.height) // 2))
    small = square.resize((size, size), Image.LANCZOS)
    r, g, b, a = small.split()  # a touch of sharpening on the colour, never on the alpha (no halo)
    small = Image.merge("RGBA", [c.filter(ImageFilter.UnsharpMask(radius=1, percent=70, threshold=0)) for c in (r, g, b)] + [a])
    return list(small.get_flattened_data() if hasattr(small, "get_flattened_data") else small.getdata())


def rgb(r, g, b):
    v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
    return ((v << 8) | (v >> 8)) & 0xFFFF


def pack(data):
    packer = zlib.compressobj(9, zlib.DEFLATED, -15)
    return packer.compress(data) + packer.flush()


def build(codes, size):
    blob, offsets, table = bytearray(), [0], []
    for cp in codes:
        data = render(cp, size)
        if data is None:
            continue
        table.append((cp, len(table)))
        pixels, alphas = [], []
        for r, g, b, a in data:
            pixels.append(rgb(r, g, b) if a else 0)  # un-premultiply is not needed: the font stores straight alpha
            alphas.append((a * 15 + 127) // 255)
        alpha = bytes((alphas[i] << 4) | alphas[i + 1] for i in range(0, len(alphas), 2))
        blob += pack(struct.pack("<%dH" % len(pixels), *pixels) + alpha)
        offsets.append(len(blob))
    return blob, offsets, table


out = ["#pragma once", "#include <stdint.h>",
       "// Generated by tools/make_color_emoji.py from Noto Color Emoji (SIL Open Font License). Do not edit.",
       "// RGB565 in panel byte order + 4-bit alpha (two pixels per byte); T-Deck Plus colour UI.",
       "// Sprite i: raw deflate of its Pixels RGB565 words (little endian) then Pixels/2 alpha bytes, Data[Offset[i]..Offset[i+1]).",
       "namespace mm_emoji_color {", "struct Entry {uint32_t code;uint16_t index;};"]
for name, codes, size in (("ChatBig", chat_codes, 20), ("Picker", picker_codes, 30)):
    blob, offsets, table = build(codes, size)
    out.append(f"constexpr int {name}Size={size},{name}Count={len(table)},{name}Pixels={size * size};")
    out.append(f"const uint8_t {name}Data[] PROGMEM={{" + ",".join(str(b) for b in blob) + "};")
    out.append(f"const uint32_t {name}Offset[] PROGMEM={{" + ",".join(str(o) for o in offsets) + "};")
    table.sort()  # sorted by codepoint: emojiColorIndex() binary-searches it (the picker list is in category order)
    out.append(f"const Entry {name}Table[] PROGMEM={{" + ",".join("{%d,%d}" % t for t in table) + "};")
    print(name, len(table), "of", len(codes), len(blob), "bytes packed")
out.append("}")
(ROOT / "src/ui/emoji_color.h").write_text("\n".join(out) + "\n")
