"""T-Deck Plus lock illustration: 320x240 PNG -> raw-deflated RGB565 in panel byte order (src/ui/lock_photo.h),
unpacked at draw time by mm::unpackPhoto (src/ui/packed.h).

The PNG is the painted Matterhorn of the "Alpine Light" concept, with the concept's overlay text removed.
Usage: python tools/make_plus_wallpaper.py <png> <header> [namespace]   (one header per theme illustration)
"""
import struct, sys, zlib
from PIL import Image

src, out = sys.argv[1], sys.argv[2]
namespace = sys.argv[3] if len(sys.argv) > 3 else "mm_lock_photo"
im = Image.open(src).convert("RGB")
assert im.size == (320, 240), im.size
words = []
for r, g, b in im.get_flattened_data() if hasattr(im, "get_flattened_data") else im.getdata():
    c = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
    words.append(((c << 8) | (c >> 8)) & 0xFFFF)  # panel byte order (see mm::rgb)
packer = zlib.compressobj(9, zlib.DEFLATED, -15)
packed = packer.compress(struct.pack("<%dH" % len(words), *words)) + packer.flush()
with open(out, "w") as f:
    f.write("#pragma once\n// Generated by tools/make_plus_wallpaper.py from %s. Do not edit.\n" % src)
    f.write("// RGB565 words (panel byte order, little endian), raw deflate: mm::unpackPhoto (ui/packed.h).\n")
    f.write("#include <stdint.h>\nnamespace %s {\nconstexpr int width=320,height=240;\n" % namespace)
    f.write("const uint8_t packed[]={\n")
    for i in range(0, len(packed), 32):
        f.write(",".join(str(v) for v in packed[i:i + 32]) + ",\n")
    f.write("};\n}\n")
print(len(words), "pixels,", len(packed), "bytes packed")
