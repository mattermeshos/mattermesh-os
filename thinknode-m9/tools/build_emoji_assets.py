"""Composer emoji picker for the T-Deck Plus, and the list of chat emoji that get a colour sprite.

src/ui/emoji_picker.h          picker code points grouped by category (faces come from src/ui/emoji_color.h) and the
                               20 px composer button face, drawn from the monochrome Noto Emoji font (OFL)
assets/config/chat-emoji.txt   chat emoji code points (hex, one per line): the previous list plus every picker emoji
Then run tools/make_color_emoji.py for the colour sprites. Run with the tools venv: python tools/build_emoji_assets.py
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / 'assets/fonts/noto-emoji/NotoEmoji-VF.ttf'
CHAT = ROOT / 'assets/config/chat-emoji.txt'

CATEGORIES = [
    ('Smileys', '😀😃😄😁😆😅😂🤣🙂😉😊😍😘😋😎🤔😐😴😢😭😡😱🤯🥶'),
    ('People', '👍👎👌✌🤞👏🙏💪👋🤝🙌👀🫡🤙✋☝👉👈🙋🤷🏃🚶🧗🎉'),
    ('Nature', '☀⛅☁🌧⛈🌩❄🌨🌫🌪🌈🌙⭐🔥💧🌊⛰🏔🌲🌻🐶🐱🐦🐟'),
    ('Travel', '📍🗺🧭⛺🏠🚗🚲🛵🚌🚆✈⛽🔋🔌📡📻📱💡🔦🎒☕🍕🍺🍷'),
    ('Symbols', '❤💔✅❌⚠❗❓⚡💯🆘🆗🔴🟢🟡🔵⬆⬇⬅➡🔁⏰🔔🔇📶'),
]


def button_face(cp, size):
    """1-bit face of the composer emoji button, MSB first, rows padded to bytes."""
    font = ImageFont.truetype(str(FONT), size * 4)
    font.set_variation_by_name('Bold')
    x, y, r, b = font.getbbox(chr(cp))
    im = Image.new('L', (r - x + 4, b - y + 4), 0)
    ImageDraw.Draw(im).text((-x + 2, -y + 2), chr(cp), font=font, fill=255)
    im = im.crop(im.getbbox())
    im.thumbnail((size, size), Image.Resampling.LANCZOS)
    cell = Image.new('L', (size, size), 0)
    cell.paste(im, ((size - im.width) // 2, (size - im.height) // 2))
    out = []
    for yy in range(size):
        row = [cell.getpixel((xx, yy)) >= 110 for xx in range(size)]
        for byte in range(0, size, 8):
            out.append(sum(1 << (7 - j) for j in range(8) if byte + j < size and row[byte + j]))
    return out


def codepoints(text):
    return [ord(c) for c in text if ord(c) not in (0xfe0f, 0x200d)]


picker = [cp for _, text in CATEGORIES for cp in codepoints(text)]
assert len(picker) == len(set(picker)), 'duplicate picker emoji'
previous = {int(l, 16) for l in CHAT.read_text().splitlines() if l.strip() and not l.startswith('#')} if CHAT.exists() else set()
chat = sorted(previous | set(picker))
CHAT.write_text('# Chat emoji with a colour sprite (tools/make_color_emoji.py): one code point per line, hex.\n' +
                ''.join('%X\n' % cp for cp in chat))

glyphs, cats = [], []
for label, text in CATEGORIES:
    cps = codepoints(text)
    cats.append('{"%s",%d,%d}' % (label, len(glyphs), len(cps)))
    glyphs += ['{%d,"%s"}' % (cp, ''.join('\\x%02x' % b for b in chr(cp).encode())) for cp in cps]
(ROOT / 'src/ui/emoji_picker.h').write_text(
    '#pragma once\n#include <stdint.h>\n// Generated by tools/build_emoji_assets.py (Noto Emoji, OFL).\nnamespace mm_emoji_picker {\n'
    'constexpr int Size=24;\n'
    '// Picker glyphs: code point and UTF-8 text; the faces are drawn from emoji_color.h.\n'
    'struct Glyph {uint32_t code;const char *text;};\n'
    'struct Category {const char *label;uint8_t first,count;};\n'
    'inline constexpr Glyph glyphs[]={' + ',\n'.join(glyphs) + '};\nconstexpr int count=sizeof(glyphs)/sizeof(glyphs[0]);\n'
    'inline constexpr Category categories[]={' + ','.join(cats) + '};\nconstexpr int categoryCount=sizeof(categories)/sizeof(categories[0]);\n'
    '// Composer button face, smaller than the picker glyphs.\nconstexpr int ButtonSize=20;\ninline constexpr uint8_t button[]={' +
    ','.join(map(str, button_face(0x1f642, 20))) + '};\n}\n')
print(len(chat), 'chat emoji,', len(glyphs), 'picker glyphs')
