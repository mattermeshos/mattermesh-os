"""Text fold table (src/ui/text_fold.h): letters and symbols the T-Deck fonts lack, drawn as the nearest letter they have.

Names on the mesh use decorated letters ("⟦MΔRȻØ⟧", "𝐌𝐀𝐑𝐂𝐎", "ᴍᴀʀᴄᴏ", "ＭＡＲＣＯ"): without a glyph they were drawn
as empty boxes. Each entry maps one code point to one the fonts draw (ASCII, Latin-1 or the Greek table). Code points
of the colour emoji set, the Cyrillic and Greek tables and the regional indicators are never folded.
Usage: python tools/make_text_fold.py
"""
import re
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
emoji = {int(a) for a in re.findall(r"\{(\d+),\d+\}", re.search(r"Entry ChatBigTable\[\] PROGMEM=\{(.*?)\};", (ROOT / "src/ui/emoji_color.h").read_text(), re.S).group(1))}
GREEK = range(0x391, 0x3CA)
CYRILLIC = range(0x400, 0x492)
LATIN_A = range(0x100, 0x180)  # drawn from the <Face>Lat tables (M9)


def drawable(cp):
    return 0x20 <= cp <= 0x7E or 0xA1 <= cp <= 0xFF or cp in GREEK or cp in LATIN_A


MANUAL = {  # no decomposition to a base letter: strokes, bars, hooks, brackets, stars
    "Ł": "L", "ł": "l", "Đ": "D", "đ": "d", "Ħ": "H", "ħ": "h", "Ŧ": "T", "ŧ": "t", "Ƶ": "Z", "ƶ": "z", "Ȼ": "C", "ȼ": "c",
    "Ɇ": "E", "ɇ": "e", "Ɍ": "R", "ɍ": "r", "Ɏ": "Y", "ɏ": "y", "Ƀ": "B", "ƀ": "b", "Ȿ": "S", "ȿ": "s", "Ɨ": "I", "ɨ": "i",
    "Ɵ": "O", "ɵ": "o", "Ƙ": "K", "ƙ": "k", "Ƒ": "F", "ƒ": "f", "Ɠ": "G", "ɠ": "g", "Ɗ": "D", "ɗ": "d", "Ɓ": "B", "ɓ": "b",
    "Ƈ": "C", "ƈ": "c", "Ƥ": "P", "ƥ": "p", "Ƭ": "T", "ƭ": "t", "Ʈ": "T", "Ʋ": "V", "Ƴ": "Y", "ƴ": "y", "Ȥ": "Z", "ȥ": "z",
    "Ŋ": "N", "ŋ": "n", "Œ": "Œ", "ı": "i", "ȷ": "j", "ĸ": "k", "ſ": "s", "Ə": "E", "ə": "e", "Ɛ": "E", "ɛ": "e", "Ɔ": "O", "ɔ": "o",
    "⟦": "[", "⟧": "]", "⟨": "<", "⟩": ">", "〈": "<", "〉": ">", "⟪": "«", "⟫": "»", "《": "«", "》": "»", "‹": "<", "›": ">",
    "「": "[", "」": "]", "『": "[", "』": "]", "【": "[", "】": "]", "〔": "[", "〕": "]", "〖": "[", "〗": "]", "⁅": "[", "⁆": "]",
    "★": "*", "☆": "*", "✦": "*", "✧": "*", "✩": "*", "✪": "*", "✫": "*", "✬": "*", "✭": "*", "✮": "*", "✯": "*", "⋆": "*",
    "•": "·", "‣": ">", "∙": "·", "⋅": "·", "―": "-", "‐": "-", "‑": "-", "‒": "-", "−": "-", "∕": "/", "⁄": "/", "∗": "*",
    "′": "'", "″": "\"", "‚": ",", "‛": "'", "‟": "\"", "∼": "~", "≈": "~",
}


def target(cp):
    ch = chr(cp)
    if ch in MANUAL:
        return MANUAL[ch]
    name = unicodedata.name(ch, "")
    m = re.match(r"LATIN LETTER SMALL CAPITAL ([A-Z])$", name)
    if m:
        return m.group(1)
    for form in ("NFKC", "NFD"):
        s = unicodedata.normalize(form, ch)
        s = "".join(c for c in s if not unicodedata.combining(c))
        if len(s) == 1 and drawable(ord(s)) and s != ch:
            return s
    return None


RANGES = [(0x100, 0x24F), (0x250, 0x2AF), (0x1D00, 0x1DBF), (0x1E00, 0x1EFF), (0x2000, 0x206F), (0x2070, 0x209F),
          (0x2100, 0x214F), (0x2190, 0x21FF), (0x2200, 0x22FF), (0x2460, 0x24FF), (0x2600, 0x27BF), (0x27E6, 0x27EF),
          (0x3000, 0x303F), (0x1F100, 0x1F1E5), (0xFF01, 0xFF5E), (0x1D400, 0x1D7FF), (0x386, 0x3CE)]
table = {}
for a, b in RANGES:
    for cp in range(a, b + 1):
        if cp in emoji or cp in GREEK or cp in CYRILLIC or cp in LATIN_A or cp in (0x2070, 0x200D, 0x2122):
            continue
        t = target(cp)
        if t is not None:
            table[cp] = ord(t)
out = ["#pragma once", "// Generated by tools/make_text_fold.py. Do not edit.",
       "// Code points the T-Deck fonts lack -> the nearest one they draw (ASCII, Latin-1, Greek table); sorted by code.",
       "#include <stdint.h>", "namespace mm_fold {", "struct Entry {uint32_t from;uint16_t to;};",
       f"constexpr int Count={len(table)};",
       "const Entry Table[Count]={" + ",".join("{%d,%d}" % (k, v) for k, v in sorted(table.items())) + "};",
       "inline uint32_t fold(uint32_t cp){int lo=0,hi=Count;while(lo<hi){int mid=(lo+hi)/2;if(Table[mid].from<cp)lo=mid+1;else hi=mid;}return lo<Count&&Table[lo].from==cp?Table[lo].to:cp;}",
       "}"]
(ROOT / "src/ui/text_fold.h").write_text("\n".join(out) + "\n")
print(len(table), "folds")
