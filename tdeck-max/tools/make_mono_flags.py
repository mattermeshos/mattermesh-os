"""T-Deck Max 1-bit flags: Noto Color Emoji flag ligatures (two regional indicators) -> src/ui/emoji_flags_mono.h.

E-paper has no colour, so each pixel of the flag is classed by colour and drawn as a pattern: white empty, yellow /
orange sparse dots, red checkerboard, green vertical lines, light blue horizontal lines, blue / purple dense, black
solid, grey checkerboard. A 1 px border closes the flag. Sprite W x H, rows MSB first, (W+7)/8 bytes per row.
Keyed by Code = (first - U+1F1E6) * 26 + (second - U+1F1E6), sorted; other pairs keep the letter badge.
Run with the tools venv: python tools/make_mono_flags.py (reads assets/fonts/NotoColorEmoji.ttf here or in the Plus tree)
"""
import colorsys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = next(p for p in (ROOT / "assets/fonts/NotoColorEmoji.ttf", ROOT.parent / "tdeck-plus-868/assets/fonts/NotoColorEmoji.ttf") if p.exists())
font = ImageFont.truetype(str(FONT), 109)
RI = 0x1F1E6
W, H = 18, 12
COUNTRIES = "AD AE AF AG AI AL AM AO AQ AR AS AT AU AW AX AZ BA BB BD BE BF BG BH BI BJ BL BM BN BO BQ BR BS BT BV BW BY BZ CA CC CD CF CG CH CI CK CL CM CN CO CR CU CV CW CX CY CZ DE DJ DK DM DO DZ EC EE EG EH ER ES ET FI FJ FK FM FO FR GA GB GD GE GF GG GH GI GL GM GN GP GQ GR GS GT GU GW GY HK HM HN HR HT HU ID IE IL IM IN IO IQ IR IS IT JE JM JO JP KE KG KH KI KM KN KP KR KW KY KZ LA LB LC LI LK LR LS LT LU LV LY MA MC MD ME MF MG MH MK ML MM MN MO MP MQ MR MS MT MU MV MW MX MY MZ NA NC NE NF NG NI NL NO NP NR NU NZ OM PA PE PF PG PH PK PL PM PN PR PS PT PW PY QA RE RO RS RU RW SA SB SC SD SE SG SH SI SJ SK SL SM SN SO SR SS ST SV SX SY SZ TC TD TF TG TH TJ TK TL TM TN TO TR TT TV TW TZ UA UG UM US UY UZ VA VC VE VG VI VN VU WF WS XK YE YT ZA ZM ZW EU UN".split()


def ink(r, g, b, x, y):
    h, s, v = colorsys.rgb_to_hsv(r / 255, g / 255, b / 255)
    h *= 360
    if v < 0.22:
        return True  # black
    if s < 0.22:
        return False if v > 0.72 else (x + y) % 2 == 0  # white / grey
    if h < 18 or h >= 330:
        return (x + y) % 2 == 0  # red: checkerboard
    if h < 70:
        return x % 2 == 0 and y % 2 == 0  # yellow / orange: sparse dots
    if h < 170:
        return x % 2 == 0  # green: vertical lines
    if h < 205 or (h < 230 and v > 0.8 and s < 0.6):
        return y % 2 == 0  # light blue: horizontal lines
    return not (x % 2 == 0 and y % 2 == 0)  # blue / purple: dense


def render(text):
    im = Image.new("RGBA", (320, 160), (0, 0, 0, 0))
    ImageDraw.Draw(im).text((8, 8), text, font=font, embedded_color=True)
    box = im.getbbox()
    if not box:
        return None
    im = im.crop(box)
    mx, my = im.width * 7 // 100, im.height * 12 // 100  # the waving edge and its shadow
    im = im.crop((mx, my, im.width - mx, im.height - my))
    flat = Image.new("RGB", im.size, (255, 255, 255))
    flat.paste(im, mask=im.split()[3])
    small = flat.resize((W - 2, H - 2), Image.NEAREST)
    rows = [[x in (0, W - 1) or y in (0, H - 1) for x in range(W)] for y in range(H)]
    for y in range(H - 2):
        for x in range(W - 2):
            rows[y + 1][x + 1] = ink(*small.getpixel((x, y)), x, y)
    return rows


def pack(rows):
    out = []
    for row in rows:
        for byte in range(0, W, 8):
            out.append(sum(1 << (7 - j) for j in range(8) if byte + j < W and row[byte + j]))
    return out


if __name__ == "__main__":
    entries = []
    for a, b in sorted((ord(c[0]) - 65, ord(c[1]) - 65) for c in COUNTRIES):
        rows = render(chr(RI + a) + chr(RI + b))
        if rows:
            entries.append((a * 26 + b, pack(rows)))
    out = ["#pragma once", "#include <stdint.h>",
           "// Generated by tools/make_mono_flags.py from Noto Color Emoji (SIL Open Font License). Do not edit.",
           "// 1-bit flags for e-paper: colours drawn as patterns, 1 px border; Code = (first - U+1F1E6) * 26 + (second - U+1F1E6), sorted.",
           "namespace mm_flags {", f"constexpr int W={W},H={H},RowBytes={(W + 7) // 8},Count={len(entries)};",
           f"struct Entry {{uint16_t code;uint8_t rows[{H * ((W + 7) // 8)}];}};",
           "const Entry Table[Count] PROGMEM={" + ",".join("{%d,{%s}}" % (c, ",".join(map(str, p))) for c, p in entries) + "};",
           "inline const Entry *find(int code){int lo=0,hi=Count;while(lo<hi){int mid=(lo+hi)/2;if(Table[mid].code<code)lo=mid+1;else hi=mid;}return lo<Count&&Table[lo].code==code?&Table[lo]:nullptr;}",
           "}"]
    (ROOT / "src/ui/emoji_flags_mono.h").write_text("\n".join(out) + "\n")
    print(len(entries), "flags")
