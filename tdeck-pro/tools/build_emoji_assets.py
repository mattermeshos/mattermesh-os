"""Generate one-bit emoji bitmaps from the monochrome Noto Emoji font (OFL).

src/ui/emoji_bitmap.h  14x14 inline glyphs for chat text (same codepoints as before;
                       codepoints the monochrome font lacks keep their previous bitmap)
src/ui/emoji_picker.h  24x24 glyphs for the composer emoji picker, grouped by category
Run with the tools venv: python tools/build_emoji_assets.py
"""
import re
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / 'assets/fonts/noto-emoji/NotoEmoji-VF.ttf'
CMAP = TTFont(FONT).getBestCmap()
# The monochrome font hatches "red" shapes; draw these with a solid stand-in glyph.
STAND_IN = {0x2764: 0x2665}

CATEGORIES = [
    ('Smileys', '😀😃😄😁😆😅😂🤣🙂😉😊😍😘😋😎🤔😐😴😢😭😡😱🤯🥶'),
    ('People', '👍👎👌✌🤞👏🙏💪👋🤝🙌👀🫡🤙✋☝👉👈🙋🤷🏃🚶🧗🎉'),
    ('Nature', '☀⛅☁🌧⛈🌩❄🌨🌫🌪🌈🌙⭐🔥💧🌊⛰🏔🌲🌻🐶🐱🐦🐟'),
    ('Travel', '📍🗺🧭⛺🏠🚗🚲🛵🚌🚆✈⛽🔋🔌📡📻📱💡🔦🎒☕🍕🍺🍷'),
    ('Symbols', '❤💔✅❌⚠❗❓⚡💯🆘🆗🔴🟢🟡🔵⬆⬇⬅➡🔁⏰🔔🔇📶'),
]


def render(cp, size):
    cp = STAND_IN.get(cp, cp)
    if cp not in CMAP:
        return None
    font = ImageFont.truetype(str(FONT), size * 4)
    font.set_variation_by_name('Bold')
    ch = chr(cp)
    x, y, r, b = font.getbbox(ch)
    im = Image.new('L', (r - x + 4, b - y + 4), 0)
    ImageDraw.Draw(im).text((-x + 2, -y + 2), ch, font=font, fill=255)
    box = im.getbbox()
    if not box:
        return None
    im = im.crop(box)
    im.thumbnail((size, size), Image.Resampling.LANCZOS)
    cell = Image.new('L', (size, size), 0)
    cell.paste(im, ((size - im.width) // 2, (size - im.height) // 2))
    return [[cell.getpixel((xx, yy)) >= 110 for xx in range(size)] for yy in range(size)]


def pack(rows):
    out = []
    for row in rows:
        for byte in range(0, len(row), 8):
            out.append(sum((1 << (7 - j)) for j in range(8) if byte + j < len(row) and row[byte + j]))
    return out


def codepoints(text):
    return [ord(c) for c in text if ord(c) not in (0xfe0f, 0x200d)]


previous = {int(code): pixels for code, pixels in re.findall(
    r'\{(\d+),\{([\d,]+)\}\}', (ROOT / 'src/ui/emoji_bitmap.h').read_text())}
picker = [cp for _, text in CATEGORIES for cp in codepoints(text)]
assert len(picker) == len(set(picker)), 'duplicate picker emoji'

inline, fallback = [], 0
for cp in sorted(set(previous) | set(picker)):
    rows = render(cp, 14)
    if rows:
        inline.append('{%d,{%s}}' % (cp, ','.join(map(str, pack(rows)))))
    elif cp in previous:
        inline.append('{%d,{%s}}' % (cp, previous[cp]))
        fallback += 1
    else:
        raise SystemExit('picker emoji missing from font: U+%04X' % cp)
(ROOT / 'src/ui/emoji_bitmap.h').write_text(
    '#pragma once\n#include <stdint.h>\n// Generated by tools/build_emoji_assets.py (Noto Emoji, OFL).\nnamespace mm_emoji {\n'
    'struct Glyph {uint32_t code;uint8_t pixels[28];};\nconst Glyph glyphs[] PROGMEM={' + ','.join(inline) +
    '};\nconstexpr int count=sizeof(glyphs)/sizeof(glyphs[0]);\n}\n')

glyphs, cats, atlas = [], [], Image.new('1', (26 * 24, 26 * len(CATEGORIES)), 1)
for row, (label, text) in enumerate(CATEGORIES):
    cps = codepoints(text)
    cats.append('{"%s",%d,%d}' % (label, len(glyphs), len(cps)))
    for col, cp in enumerate(cps):
        rows = render(cp, 24)
        assert rows, 'U+%04X' % cp
        utf8 = ''.join('\\x%02x' % b for b in chr(cp).encode())
        glyphs.append('{%d,"%s",{%s}}' % (cp, utf8, ','.join(map(str, pack(rows)))))
        for yy in range(24):
            for xx in range(24):
                if rows[yy][xx]:
                    atlas.putpixel((col * 26 + 1 + xx, row * 26 + 1 + yy), 0)
(ROOT / 'src/ui/emoji_picker.h').write_text(
    '#pragma once\n#include <stdint.h>\n// Generated by tools/build_emoji_assets.py (Noto Emoji, OFL).\nnamespace mm_emoji_picker {\n'
    'constexpr int Size=24;\nstruct Glyph {uint32_t code;const char *text;uint8_t pixels[72];};\n'
    'struct Category {const char *label;uint8_t first,count;};\n'
    'inline constexpr Glyph glyphs[]={' + ',\n'.join(glyphs) + '};\nconstexpr int count=sizeof(glyphs)/sizeof(glyphs[0]);\n'
    'inline constexpr Category categories[]={' + ','.join(cats) + '};\nconstexpr int categoryCount=sizeof(categories)/sizeof(categories[0]);\n'
    '// Composer button face, smaller than the picker glyphs.\nconstexpr int ButtonSize=20;\ninline constexpr uint8_t button[]={' + ','.join(map(str, pack(render(0x1f642, 20)))) + '};\n}\n')
atlas.resize((atlas.width * 2, atlas.height * 2), Image.Resampling.NEAREST).save(ROOT / 'screenshots/mattermesh/emoji-picker-atlas.png')
print(len(inline), 'inline glyphs (', fallback, 'kept from previous set ),', len(glyphs), 'picker glyphs')
