"""Import the MatterMesh OS e-ink icon pack (user artwork) for the Home tabs and App grid.

Usage:
  python tools/import_icon_pack.py extract PACK.png APP.png   # crop glyphs -> assets/icons/pack/*.png
  python tools/import_icon_pack.py build                      # assets/icons/pack/*.png -> src/ui/icon_pack_bitmap.h

The pack sheet is a 5x6 grid of labelled cells (1122x1402); APP.png is the
separate "App" artwork. Only the icons the firmware uses are kept. Glyphs are
stored at <=128 px so the build step is reproducible without the originals.
"""
import sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
PACK_DIR = ROOT / 'assets/icons/pack'
HEADER = ROOT / 'src/ui/icon_pack_bitmap.h'
COLUMNS = [(30, 228), (243, 445), (462, 660), (677, 880), (897, 1092)]
ROWS = [(137, 325), (343, 532), (550, 736), (754, 941), (958, 1149), (1166, 1363)]
CELLS = {'chat': (0, 0), 'contacts': (0, 1), 'map': (0, 2), 'weather': (0, 3), 'files': (1, 1),
         'settings': (1, 4), 'signal': (3, 3), 'tools': (5, 4), 'list': (5, 2), 'radio': (1, 2), 'keyboard': (4, 1)}
ORDER = ['chat', 'contacts', 'settings', 'apps', 'map', 'files', 'weather', 'signal', 'tools', 'list', 'radio', 'keyboard']  # = mm::PackIcon
SIZES = (24, 32)


def glyph(image, box):
    crop = image.crop(box)
    bounds = crop.point(lambda v: 255 if v < 128 else 0).getbbox()
    crop = crop.crop(bounds)
    crop.thumbnail((128, 128), Image.Resampling.LANCZOS)
    return crop


def extract(pack_path, app_path):
    PACK_DIR.mkdir(parents=True, exist_ok=True)
    pack = Image.open(pack_path).convert('L')
    for name, (row, column) in CELLS.items():
        x0, x1 = COLUMNS[column]
        y0, y1 = ROWS[row]
        glyph(pack, (x0 + 14, y0 + 14, x1 - 14, y1 - 50)).save(PACK_DIR / f'{name}.png')  # skip border and label
    glyph(Image.open(app_path).convert('L'), (300, 120, 1150, 800)).save(PACK_DIR / 'apps.png')  # above "App"


def bitmap(path, size):
    source = Image.open(path).convert('L')
    side = max(source.size)
    square = Image.new('L', (side, side), 255)
    square.paste(source, ((side - source.width) // 2, (side - source.height) // 2))
    inner = square.resize((size - 2, size - 2), Image.Resampling.LANCZOS)
    full = Image.new('L', (size, size), 255)
    full.paste(inner, (1, 1))
    bits = []
    for y in range(size):
        for x in range(size):
            bits.append(1 if full.getpixel((x, y)) < 150 else 0)
    return bytes(sum(bits[i + j] << (7 - j) for j in range(8)) for i in range(0, len(bits), 8))


def build():
    lines = ['#pragma once', '#include <Arduino.h>', '// Generated by tools/import_icon_pack.py from assets/icons/pack.', 'namespace mm_assets {']
    for size in SIZES:
        for name in ORDER:
            raw = bitmap(PACK_DIR / f'{name}.png', size)
            lines.append(f'const uint8_t pack_{name}_{size}[] PROGMEM={{' + ','.join(f'0x{v:02x}' for v in raw) + '};')
        lines.append(f'const uint8_t *const pack_icons_{size}[]={{' + ','.join(f'pack_{n}_{size}' for n in ORDER) + '};')
    lines.append('}')
    HEADER.write_text('\n'.join(lines) + '\n')
    print(f'{len(ORDER)} pack icons x {len(SIZES)} sizes -> {HEADER.relative_to(ROOT)}')


if __name__ == '__main__':
    if len(sys.argv) == 4 and sys.argv[1] == 'extract':
        extract(sys.argv[2], sys.argv[3])
    elif len(sys.argv) == 2 and sys.argv[1] == 'build':
        build()
    else:
        sys.exit(__doc__)
