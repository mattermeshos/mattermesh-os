"""T-Deck Plus colour flags: Noto Color Emoji flag ligatures (two regional indicators) -> src/ui/emoji_flags.h.

Same sprite format as tools/make_color_emoji.py (20 px, RGB565 panel order + 4-bit alpha, each sprite raw-deflated).
A flag is keyed by Code = (first - U+1F1E6) * 26 + (second - U+1F1E6); only ISO 3166 countries (+ XK, EU, UN) get a
sprite; other pairs keep the letter badge.
Run with the tools venv: python tools/make_color_flags.py
"""
import struct
import zlib
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
font = ImageFont.truetype(str(ROOT / "assets/fonts/NotoColorEmoji.ttf"), 109)
RI = 0x1F1E6
SIZE = 20


def draw(text):
    im = Image.new("RGBA", (320, 160), (0, 0, 0, 0))
    ImageDraw.Draw(im).text((8, 8), text, font=font, embedded_color=True)
    return im


def render(text):
    im = draw(text)
    bbox = im.getbbox()
    if not bbox:
        return None
    im = im.crop(bbox)
    side = max(im.width, im.height)
    square = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    square.paste(im, ((side - im.width) // 2, (side - im.height) // 2))
    small = square.resize((SIZE, SIZE), Image.LANCZOS)
    r, g, b, a = small.split()
    small = Image.merge("RGBA", [c.filter(ImageFilter.UnsharpMask(radius=1, percent=70, threshold=0)) for c in (r, g, b)] + [a])
    return list(small.get_flattened_data() if hasattr(small, "get_flattened_data") else small.getdata())


def rgb(r, g, b):
    v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
    return ((v << 8) | (v >> 8)) & 0xFFFF


def pack(data):
    packer = zlib.compressobj(9, zlib.DEFLATED, -15)
    return packer.compress(data) + packer.flush()


blob, offsets, table = bytearray(), [0], []
COUNTRIES = "AD AE AF AG AI AL AM AO AQ AR AS AT AU AW AX AZ BA BB BD BE BF BG BH BI BJ BL BM BN BO BQ BR BS BT BV BW BY BZ CA CC CD CF CG CH CI CK CL CM CN CO CR CU CV CW CX CY CZ DE DJ DK DM DO DZ EC EE EG EH ER ES ET FI FJ FK FM FO FR GA GB GD GE GF GG GH GI GL GM GN GP GQ GR GS GT GU GW GY HK HM HN HR HT HU ID IE IL IM IN IO IQ IR IS IT JE JM JO JP KE KG KH KI KM KN KP KR KW KY KZ LA LB LC LI LK LR LS LT LU LV LY MA MC MD ME MF MG MH MK ML MM MN MO MP MQ MR MS MT MU MV MW MX MY MZ NA NC NE NF NG NI NL NO NP NR NU NZ OM PA PE PF PG PH PK PL PM PN PR PS PT PW PY QA RE RO RS RU RW SA SB SC SD SE SG SH SI SJ SK SL SM SN SO SR SS ST SV SX SY SZ TC TD TF TG TH TJ TK TL TM TN TO TR TT TV TW TZ UA UG UM US UY UZ VA VC VE VG VI VN VU WF WS XK YE YT ZA ZM ZW EU UN".split()
for a, b in sorted((ord(c[0]) - 65, ord(c[1]) - 65) for c in COUNTRIES):
    data = render(chr(RI + a) + chr(RI + b))
    if data is None:
        continue
    table.append((a * 26 + b, len(table)))
    pixels = [rgb(r, g, b_) if al else 0 for r, g, b_, al in data]
    alphas = [(al * 15 + 127) // 255 for _, _, _, al in data]
    alpha = bytes((alphas[i] << 4) | alphas[i + 1] for i in range(0, len(alphas), 2))
    blob += pack(struct.pack("<%dH" % len(pixels), *pixels) + alpha)
    offsets.append(len(blob))
out = ["#pragma once", "#include <stdint.h>",
       "// Generated by tools/make_color_flags.py from Noto Color Emoji (SIL Open Font License). Do not edit.",
       "// Flag sprites, same format as emoji_color.h ChatBig; Code = (first - U+1F1E6) * 26 + (second - U+1F1E6), sorted.",
       "namespace mm_emoji_flags {", "struct Entry {uint16_t code;uint16_t index;};",
       f"constexpr int Size={SIZE},Count={len(table)},Pixels={SIZE * SIZE};",
       "const uint8_t Data[] PROGMEM={" + ",".join(str(x) for x in blob) + "};",
       "const uint32_t Offset[] PROGMEM={" + ",".join(str(o) for o in offsets) + "};",
       "const Entry Table[] PROGMEM={" + ",".join("{%d,%d}" % t for t in table) + "};", "}"]
(ROOT / "src/ui/emoji_flags.h").write_text("\n".join(out) + "\n")
print(len(table), "flags", len(blob), "bytes packed")
