"""T-Deck Plus anti-aliased UI icons: Material Design Icons (Apache 2.0, assets/fonts/mdi) -> 4-bit coverage sprites.

src/ui/aa_icons.h holds every mm::Icon and mm::PackIcon at 12, 16, 24 and 32 px, one 4-bit coverage value per pixel
(two pixels per byte, row-major, high nibble first), drawn by mm::FastCanvas16::drawAlpha in the theme ink.
Icons are rendered on the MDI 24-unit grid (the em box) at 4x and box-filtered, so strokes stay crisp and the
set keeps its common padding. Usage: python tools/make_aa_icons.py
"""
import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "assets/fonts/mdi/materialdesignicons-webfont.ttf"
CODEPOINTS = json.loads((ROOT / "assets/fonts/mdi/codepoints.json").read_text())
SIZES = [12, 16, 24, 32]
# order = enum mm::Icon, then enum mm::PackIcon
ICONS = [
    ("Messages", "message-text-outline"), ("Mesh", "hub-outline"), ("Weather", "weather-partly-cloudy"),
    ("Radio", "radio-tower"), ("Files", "folder-outline"), ("Terminal", "console"), ("Notes", "note-text-outline"),
    ("Tools", "tools"), ("Settings", "cog-outline"), ("GPS", "crosshairs-gps"), ("Info", "information-outline"),
    ("Battery", "battery-70"), ("Signal", "signal"), ("Wifi", "wifi"), ("Bluetooth", "bluetooth"),
    ("Contacts", "account-group-outline"), ("Keyboard", "keyboard-outline"), ("Flashlight", "flashlight"), ("Clock", "clock-outline"), ("Lock", "lock-outline"), ("Power", "power"),
    ("Back", "chevron-left"), ("Search", "magnify"), ("Compose", "pencil-outline"), ("Menu", "menu"), ("Plus", "plus"), ("ChevronRight", "chevron-right"), ("Mountain", "image-filter-hdr"),
    ("Antenna", "antenna"),
]
PACK = [
    ("Chat", "forum"), ("Contacts", "account-group"), ("Settings", "cog"), ("Apps", "view-grid"), ("Map", "map"),
    ("Files", "folder"), ("Weather", "weather-partly-cloudy"), ("Signal", "antenna"), ("Tools", "wrench"),
    ("List", "format-list-bulleted"), ("Radio", "radio"), ("Keyboard", "keyboard"), ("Trail", "hiking"), ("Plane", "airplane"), ("Spectrum", "chart-bell-curve"),
]
# order = enum WeatherGlyph (ui/weather_icons.h): Clear, PartlyCloudy, Cloudy, Fog, Drizzle, Rain, Snow, Storm, Unknown
WEATHER = ["weather-sunny", "weather-partly-cloudy", "weather-cloudy", "weather-fog", "weather-rainy", "weather-pouring",
           "weather-snowy", "weather-lightning-rainy", "weather-cloudy-alert"]
WEATHER_SIZES = [26, 30, 64]  # hourly strip, Home header, Weather hero
OVER = 4


def render(name, size):
    font = ImageFont.truetype(str(FONT), size * OVER)
    im = Image.new("L", (size * OVER, size * OVER), 0)
    ImageDraw.Draw(im).text((0, 0), chr(CODEPOINTS[name]), font=font, fill=255, anchor="la")
    small = im.resize((size, size), Image.BOX)
    values = list(small.getdata())
    return [(v * 15 + 127) // 255 for v in values]


out = ["#pragma once", "#include <stdint.h>",
       "// Generated by tools/make_aa_icons.py from Material Design Icons (Apache License 2.0, assets/fonts/mdi/LICENSE). Do not edit.",
       "// 4-bit coverage sprites (two pixels per byte, high nibble first), index = mm::Icon then mm::PackIcon; T-Deck Plus colour UI.",
       "namespace mm_aa_icons {", f"constexpr int IconCount={len(ICONS)},PackCount={len(PACK)},PackFirst={len(ICONS)};"]
for size in SIZES:
    data = bytearray()
    for _, mdi in ICONS + PACK:
        v = render(mdi, size)
        data.extend((v[i] << 4) | v[i + 1] for i in range(0, len(v), 2))
    out.append(f"constexpr int Stride{size}={size * size // 2};")
    out.append(f"const uint8_t Icons{size}[] PROGMEM={{" + ",".join(str(b) for b in data) + "};")
for size in WEATHER_SIZES:
    data = bytearray()
    for mdi in WEATHER:
        v = render(mdi, size)
        data.extend((v[i] << 4) | v[i + 1] for i in range(0, len(v), 2))
    out.append(f"const uint8_t Weather{size}[] PROGMEM={{" + ",".join(str(b) for b in data) + "};")
out.append("inline const uint8_t *weather(int size,int index){const uint8_t *set=size==26?Weather26:size==30?Weather30:size==64?Weather64:nullptr;return set?set+index*(size*size/2):nullptr;}")
out.append("inline const uint8_t *sprite(int size,int index){const uint8_t *set=size==12?Icons12:size==16?Icons16:size==24?Icons24:Icons32;return set+index*(size*size/2);}")
out.append("}")
(ROOT / "src/ui/aa_icons.h").write_text("\n".join(out) + "\n")
print("icons:", len(ICONS), "pack:", len(PACK), "sizes:", SIZES)
