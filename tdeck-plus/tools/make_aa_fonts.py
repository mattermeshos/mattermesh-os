"""T-Deck Plus anti-aliased UI fonts: Inter (SIL OFL, assets/fonts/inter) -> 4-bit alpha GFX fonts (src/ui/aa_fonts.h).

Each mm::Font face of the e-paper UI gets an Inter face whose cap height equals that face's ascent, so text keeps
its layout. Glyph bitmaps hold one 4-bit coverage value per pixel (two pixels per byte, row-major, high nibble
first); ui/fast_canvas.h blends them over the frame. Text faces cover 32..255 (ASCII and Latin-1: à è é ì ò ù ...),
clock faces 32..58. Text faces also get a Cyrillic table (<Face>Cyr, U+0400..U+0491 for Russian / Ukrainian): GFXfont
cannot address code points above 255, so its code 32 is U+0400 and Components draws cp as cp-0x400+32. A Greek table
(<Face>Grk, U+0391..U+03C9) works the same way.
Usage: python tools/make_aa_fonts.py
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "assets/fonts/inter"
# name, weight, cap height (= Components::ascent), line height (= Components::lineHeight); order = enum mm::Font
FACES = [
    ("Small", "Medium", 10, 11), ("Body", "Medium", 10, 13), ("Bold", "Bold", 10, 13), ("Title", "Bold", 12, 16),
    ("Brand", "Bold", 17, 21), ("Clock", "Bold", 28, 34), ("Tiny", "SemiBold", 7, 9), ("HomeClock", "Bold", 48, 64),
    ("LockText", "SemiBold", 11, 17), ("ChatBody", "Medium", 10, 15), ("ChatMeta", "Medium", 9, 13),
    ("ChatTitle", "Bold", 13, 20), ("MenuClock", "Bold", 30, 44), ("MenuLabel", "SemiBold", 7, 11),
    ("LockClock", "Bold", 47, 64), ("NavLabel", "SemiBold", 9, 13), ("ChatText", "Medium", 12, 17), ("ChatTextSmall", "Medium", 11, 16),
]


def cap_height(font):
    box = font.getbbox("H", anchor="ls")
    return box[3] - box[1]


def face(weight, cap):
    path = str(FONTS / f"Inter-{weight}.ttf")
    best = None
    for size in range(5, 120):
        f = ImageFont.truetype(path, size)
        d = abs(cap_height(f) - cap)
        if best is None or d < best[0]:  # ties: the smaller size (narrower text keeps the layouts)
            best = (d, f, size)
    return best[1], best[2]


# Word space: Inter's 0.28 em is 3 px at these sizes, so a typed space barely moves the caret; widen it.
WIDE_SPACE = {"ChatText": 0.38, "ChatTextSmall": 0.38, "ChatBody": 0.38, "LockText": 0.35}


CYR_FIRST, CYR_LAST = 0x400, 0x491
GRK_FIRST, GRK_LAST = 0x391, 0x3C9  # Greek capitals and small letters (names like "MΔRCO", Ω, π)


def glyphs(font, last, space_em=0.32, codes=None):
    bitmap, table = bytearray(), []
    for code in (codes if codes is not None else range(32, last + 1)):
        ch = chr(code)
        if 127 <= code < 160 or code == 0xAD or 0x483 <= code <= 0x489:  # controls, soft hyphen, combining marks: no ink
            table.append((len(bitmap), 0, 0, 0, 0, 0))
            continue
        if code == 0xA0:  # no-break space draws as a space
            ch = " "
        advance = round(font.getlength(ch))
        if ch == " ":
            advance = max(advance, round(font.size * space_em))
        box = font.getbbox(ch, anchor="ls")
        w, h = box[2] - box[0], box[3] - box[1]
        if ch == " " or w <= 0 or h <= 0:
            table.append((len(bitmap), 0, 0, advance, 0, 0))
            continue
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((-box[0], -box[1]), ch, font=font, fill=255, anchor="ls")
        offset = len(bitmap)
        values = [(v * 15 + 127) // 255 for v in (im.get_flattened_data() if hasattr(im, 'get_flattened_data') else im.getdata())]
        if len(values) % 2:
            values.append(0)
        bitmap.extend((values[i] << 4) | values[i + 1] for i in range(0, len(values), 2))
        table.append((offset, w, h, advance, box[0], box[1]))
    return bitmap, table


out = ["#pragma once",
       "// Generated by tools/make_aa_fonts.py from Inter (SIL Open Font License, assets/fonts/inter/OFL.txt). Do not edit.",
       "// 4-bit coverage per pixel, two pixels per byte; drawn by mm::FastCanvas16 (T-Deck Plus colour UI).",
       "#include <Adafruit_GFX.h>", "namespace mm_aa {"]
names = []
bitmaps, tables = {}, {}
for name, weight, cap, line in FACES:
    font, size = face(weight, cap)
    last = 58 if name.endswith("Clock") else 255  # clock faces: digits and colon (GFXglyph offsets are 16-bit)
    bitmap, table = glyphs(font, last, WIDE_SPACE.get(name, 0.32))
    assert len(bitmap) < 65536, name
    out.append(f"// {name}: Inter {weight} {size}px, cap {cap_height(font)} (target {cap}), line {line}")
    # Faces that render to the same pixels share one bitmap / glyph table in flash (Small, Body and ChatMeta, ...).
    bkey, gkey = bytes(bitmap), tuple(table)
    bname = bitmaps.setdefault(bkey, name)
    gname = tables.setdefault((bname, gkey), name)
    if bname == name:
        out.append(f"const uint8_t {name}Bitmap[] PROGMEM={{" + ",".join(str(b) for b in bitmap) + "};")
    if gname == name:
        out.append(f"const GFXglyph {name}Glyphs[] PROGMEM={{" + ",".join("{%d,%d,%d,%d,%d,%d}" % g for g in table) + "};")
    out.append(f"const GFXfont {name} PROGMEM={{(uint8_t*){bname}Bitmap,(GFXglyph*){gname}Glyphs,32,{last},{line}}};")
    names.append(name)
    if not name.endswith("Clock"):  # Cyrillic table of the same face
        cbitmap, ctable = glyphs(font, 0, codes=range(CYR_FIRST, CYR_LAST + 1))
        assert len(cbitmap) < 65536, name
        cname = name + "Cyr";cbname = bitmaps.setdefault(bytes(cbitmap), cname);cgname = tables.setdefault((cbname, tuple(ctable)), cname)
        if cbname == cname:
            out.append(f"const uint8_t {cname}Bitmap[] PROGMEM={{" + ",".join(str(b) for b in cbitmap) + "};")
        if cgname == cname:
            out.append(f"const GFXglyph {cname}Glyphs[] PROGMEM={{" + ",".join("{%d,%d,%d,%d,%d,%d}" % g for g in ctable) + "};")
        out.append(f"const GFXfont {cname} PROGMEM={{(uint8_t*){cbname}Bitmap,(GFXglyph*){cgname}Glyphs,32,{32 + CYR_LAST - CYR_FIRST},{line}}};")
        gbitmap, gtable = glyphs(font, 0, codes=range(GRK_FIRST, GRK_LAST + 1))
        gname_ = name + "Grk";gbname = bitmaps.setdefault(bytes(gbitmap), gname_);ggname = tables.setdefault((gbname, tuple(gtable)), gname_)
        if gbname == gname_:
            out.append(f"const uint8_t {gname_}Bitmap[] PROGMEM={{" + ",".join(str(b) for b in gbitmap) + "};")
        if ggname == gname_:
            out.append(f"const GFXglyph {gname_}Glyphs[] PROGMEM={{" + ",".join("{%d,%d,%d,%d,%d,%d}" % g for g in gtable) + "};")
        out.append(f"const GFXfont {gname_} PROGMEM={{(uint8_t*){gbname}Bitmap,(GFXglyph*){ggname}Glyphs,32,{32 + GRK_LAST - GRK_FIRST},{line}}};")
out.append("}")
(ROOT / "src/ui/aa_fonts.h").write_text("\n".join(out) + "\n")
print("faces:", ", ".join(names))
